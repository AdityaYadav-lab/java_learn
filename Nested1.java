public class Nested1 {
    public static void main (String args[]){
        // Number Pattern 
        for (int i =1 ; i<=5 ; i++){
            
            for (int j=1 ; j<=i; j++){
                System.out.print(j);
            }
            System.out.println();
        }
      // Reverse Number Pattern
          for (int i =5 ; i>=1 ; i--){ 
            for (int j=1 ; j<=i; j++){
                System.out.print(j);
            }
             System.out.println();
          }
       
      }
}
